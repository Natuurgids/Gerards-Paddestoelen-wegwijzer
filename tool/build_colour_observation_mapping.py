"""Compile photographic colour metadata; --check detects stale UI mappings."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(check=False):
    catalogue = json.loads((ROOT / 'assets/data/identification_traits.json').read_text())
    styles = {}
    lines = ['// Generated by tool/build_colour_observation_mapping.py.',
             '// Neutral photographic textures are coloured only on the observed structure.',
             "const bruisePatchAsset = 'determination_wheel/assets/colour_photographs/bruise.png';",
             'const colourObservationStyles = <int,({String trait, String asset, int? tint, String kind})>{']
    for trait in catalogue['traits']:
        for option in trait['options']:
            visual = option.get('colour_visual')
            if visual is None:
                continue
            tint, kind = visual['tint'], visual['kind']
            assert kind in {'single', 'none', 'uncertain', 'not_applicable', 'multicoloured', 'red_then_black'}
            assert tint is None or len(tint) == 6 and all(c in '0123456789abcdef' for c in tint)
            assert (ROOT / option['image']).is_file()
            styles[str(option['id'])] = {'trait': trait['code'], 'asset': option['image'], 'tint': tint, 'kind': kind}
            argb = '0xff' + tint if tint else 'null'
            lines.append("  %d: (trait: '%s', asset: '%s', tint: %s, kind: '%s')," %
                         (option['id'], trait['code'], option['image'], argb, kind))
    lines.append('};')
    assert len(styles) == 120
    assert styles['226']['tint'] == '568b50'  # green bruising must not inherit red/brown imagery
    assert styles['19']['tint'] is None and styles['19']['kind'] == 'none'
    for path, content in [
        ('lib/src/features/identify/colour_observation_data.dart', '\n'.join(lines) + '\n'),
        ('assets/data/observation_colour_styles.json', json.dumps(styles, ensure_ascii=False, indent=2) + '\n'),
    ]:
        target = ROOT / path
        if check:
            assert target.read_text() == content, f'Stale generated mapping: {path}'
        else:
            target.write_text(content)
    print('PASS: 120 photographic colour observations have explicit, current mappings.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
