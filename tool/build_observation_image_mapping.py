"""Compile current packaged images so cached rows cannot override fixes."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def build(check=False):
    data = json.loads((ROOT / 'assets/data/identification_traits.json').read_text())
    lines = ['// Generated by tool/build_observation_image_mapping.py.', 'const observationImages = <int, ({String trait, String code, String asset})>{']
    for trait in data['traits']:
        for option in trait['options']:
            fields = ', '.join(f'{name}: {json.dumps(value)}' for name, value in [('trait', trait['code']), ('code', option['code']), ('asset', option['image'])])
            lines.append(f"  {option['id']}: ({fields}),")
    lines += ['};', '']
    output = '\n'.join(lines)
    path = ROOT / 'lib/src/features/identify/observation_image_data.dart'
    if check:
        assert path.read_text() == output, 'Observation image mapping is stale.'
    else:
        path.write_text(output)
    print('PASS: 350 packaged image mappings cover all 341 active observation choices.')
if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
